    <h1>ПУБЛИЧНЫЙ ДОГОВОР-ОФЕРТА</h1>
    <p class="legal-subtitle">Общественного объединения «Казахстанское общество врачей любителей футбола»<br>(далее – Организатор)</p>

    <p>Настоящая публичная оферта (далее – Оферта) является договором, заключённым между Организатором и участником – физическим лицом (далее – Участник), и определяет условия регистрации, уплаты членского взноса и участия в любительских футбольных турнирах, организуемых Организатором на портале kmft.kz.</p>

    <h2>1. Общие положения</h2>
    <p>1.1. Организатор публикует настоящую Оферту в соответствии со ст. 395, 396 и 447 Гражданского кодекса Республики Казахстан (далее – ГК РК).</p>
    <p>1.2. Оферта определяет существенные условия взаимодействия между Организатором и Участником.</p>
    <p>1.3. Договор считается заключённым с момента акцепта Оферты — завершения регистрации Участника на портале kmft.kz.</p>
    <p>1.4. Регистрация на портале носит закрытый характер: самостоятельная регистрация без предварительного внесения номера телефона Администратором платформы невозможна.</p>
    <p>1.5. Принимая условия Оферты, Участник безоговорочно соглашается со всеми её положениями в полном объёме и без исключений.</p>
    <p>1.6. Акцептом является факт завершения регистрации Участника на портале kmft.kz.</p>

    <h2>2. Предмет оферты</h2>
    <p>2.1. Организатор организует и проводит любительские футбольные турниры среди медицинских работников на условиях, определённых настоящей Офертой.</p>
    <p>2.2. Участие возможно в двух статусах: Капитан команды и Игрок команды. Права и обязанности каждого статуса определяются настоящей Офертой.</p>
    <p>2.3. К отношениям между Участником и Организатором применяются положения ГК РК и иных нормативных правовых актов Республики Казахстан.</p>

    <h2>3. Порядок регистрации</h2>
    <p>3.1. Регистрация на портале kmft.kz является закрытой и осуществляется в следующем порядке:</p>
    <ul>
        <li>Администратор платформы вносит номер телефона Капитана в систему;</li>
        <li>Капитан проходит регистрацию на портале kmft.kz по внесённому номеру телефона;</li>
        <li>Капитан уплачивает ежегодный членский взнос;</li>
        <li>После подтверждения оплаты Капитан получает право формировать команду и приглашать Игроков;</li>
        <li>Игрок регистрируется на портале по приглашению Капитана и уплачивает ежегодный членский взнос.</li>
    </ul>
    <p>3.2. Лица, номера телефонов которых не внесены Администратором или не получившие приглашение от Капитана, не имеют возможности зарегистрироваться на портале.</p>
    <p>3.3. При регистрации Участник предоставляет: фамилию, имя, отчество, ИИН, номер телефона и иные данные, предусмотренные регистрационной формой.</p>

    <h2>4. Статус Участника</h2>
    <p>4.1. Участник несёт ответственность за достоверность данных, указанных при регистрации.</p>
    <p>4.2. Участник подтверждает согласие с условиями Оферты путём проставления отметки при завершении регистрации.</p>
    <p>4.3. Участник подтверждает, что его состояние здоровья позволяет участвовать в футбольных соревнованиях, и принимает на себя все риски, связанные с участием в спортивных мероприятиях.</p>
    <p>4.4. Участник обязуется соблюдать регламент турниров и правила спортивной этики.</p>

    <h2>5. Членский взнос</h2>
    <p>5.1. Размер ежегодного членского взноса составляет 15 000 (пятнадцать тысяч) тенге за одного Участника.</p>
    <p>5.2. Взнос уплачивается один раз в год и даёт право на участие во всех турнирах Организатора в течение соответствующего календарного года.</p>
    <p>5.3. Членский взнос уплачивается каждым Участником самостоятельно — как Капитаном, так и Игроком.</p>
    <p>5.4. Организатор вправе изменить размер взноса для следующего года. Уплаченный взнос пересмотру не подлежит.</p>

    <h2>6. Порядок оплаты</h2>
    <p>6.1. Оплата членского взноса осуществляется онлайн банковской картой через платёжную форму на портале kmft.kz.</p>
    <p>6.2. Все расчёты осуществляются в тенге Республики Казахстан.</p>
    <p>6.3. Участие в турнирах становится доступным после подтверждения факта оплаты в системе.</p>

    <h2>7. Возврат взноса</h2>
    <p>7.1. Участник вправе отказаться от членства и потребовать возврата взноса в порядке, установленном законодательством РК.</p>
    <p>7.2. Возврат производится в полном объёме при условии, что Участник не принимал участия ни в одном турнире в текущем году и подал заявление на возврат не позднее 14 (четырнадцати) календарных дней с даты оплаты.</p>
    <p>7.3. По истечении 14 дней с момента оплаты либо после участия хотя бы в одном турнире возврат взноса не производится.</p>
    <p>7.4. При отмене всех запланированных турниров по инициативе Организатора взнос возвращается в полном объёме.</p>

